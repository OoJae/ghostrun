// Writes THIRD_PARTY_NOTICES.md at the repo root from what actually ships: every production
// dependency in the workspace (pnpm's licence list, with each package's own licence text), the
// native code compiled into the wasm we serve, and the 3D models' provenance file. Run before a
// release: node tools/notices/build.mjs
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const ALLOWED = new Set(["MIT", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "ISC", "CC0-1.0", "Zlib", "0BSD"]);

const list = JSON.parse(execFileSync("pnpm", ["licenses", "list", "--prod", "--json", "-r"], { cwd: root, encoding: "utf8" }));
const pkgs = Object.entries(list).flatMap(([licence, ps]) => ps.map((p) => ({ ...p, licence })));
pkgs.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));

const bad = pkgs.filter((p) => !ALLOWED.has(p.licence));
if (bad.length) throw new Error(`licences outside the allowed list: ${bad.map((p) => `${p.name} (${p.licence})`).join(", ")}`);

/** The package's own licence file, as shipped in its tarball. */
function licenceText(path) {
  if (!path || !existsSync(path)) return null;
  const f = readdirSync(path).find((n) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(n));
  return f ? readFileSync(join(path, f), "utf8").trim() : null;
}

const models = JSON.parse(readFileSync(join(root, "apps/web/public/models/provenance.json"), "utf8"));

const out = [
  "# Third-party notices",
  "",
  "GHOSTRUN is MIT-licensed (see `LICENSE`). It ships the components below, each under its own licence. This file is generated by `tools/notices/build.mjs` from the production dependency tree and the 3D models' provenance; regenerate it before a release.",
  "",
  "## Summary",
  "",
  "| Component | Version | Licence |",
  "|---|---|---|",
  ...pkgs.map((p) => `| ${p.name} | ${p.versions.join(", ")} | ${p.licence} |`),
  "| Recast/Detour (compiled into @recast-navigation/wasm) | bundled | Zlib |",
  `| 3D characters and props: KayKit by ${models.author} | downloaded ${models.downloaded} | CC0-1.0 |`,
  "",
  "## Native code inside the wasm",
  "",
  "`@recast-navigation/wasm` compiles Recast and Detour (Copyright (c) 2009 Mikko Mononen), distributed under the Zlib licence: This software is provided 'as-is', without any express or implied warranty. In no event will the authors be held liable for any damages arising from the use of this software. Permission is granted to anyone to use this software for any purpose, including commercial applications, and to alter it and redistribute it freely, subject to the following restrictions: 1. The origin of this software must not be misrepresented; you must not claim that you wrote the original software. If you use this software in a product, an acknowledgment in the product documentation would be appreciated but is not required. 2. Altered source versions must be plainly marked as such, and must not be misrepresented as being the original software. 3. This notice may not be removed or altered from any source distribution.",
  "",
  "## 3D models",
  "",
  `${models.about} Licence: ${models.licence}. Optimised with ${models.optimised}. The full list of files, packs and source paths is in \`apps/web/public/models/provenance.json\`.`,
  "",
  "## Licence texts",
  "",
];
for (const p of pkgs) {
  const text = licenceText(p.paths?.[0]);
  out.push(`### ${p.name} ${p.versions.join(", ")} (${p.licence})`, "");
  if (p.homepage) out.push(`${p.homepage}`, "");
  out.push(text ? "```\n" + text + "\n```" : `(No licence file in the package; its package.json declares ${p.licence}.)`, "");
}
writeFileSync(join(root, "THIRD_PARTY_NOTICES.md"), out.join("\n"));
console.log(`THIRD_PARTY_NOTICES.md: ${pkgs.length} packages, the wasm's Zlib code, and the CC0 models`);
